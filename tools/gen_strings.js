// Localization table generator: src/strings.json -> src/ocstr.h, src/ocstr.cpp
//
// Why a generator rather than text directly in code. GCCE is old, and there is no
// reason to rely on it correctly converting UTF-8 inside L"..." to UTF-16:
// an error here would be silent and only show up on the device screen. Therefore,
// .cpp receives only escapes of the form backslash-x-XXXX, i.e. pure ASCII, while the
// readable source remains in JSON. Each line is duplicated with a comment.
//
// A language may be PARTIALLY translated. A missing string becomes NULL in the table,
// and OcStr substitutes the English one. This is a deliberate choice: service formats
// with register names are not worth translating into fifteen languages, while text
// explaining hazards must be accurate - so help remains only in languages where it was
// written, rather than machine-multiplied.
//
// Run: node tools/gen_strings.js
'use strict';
const fs = require('fs');

const data = JSON.parse(fs.readFileSync('src/strings.json', 'utf8'));
const langs = data.languages;          // first language is the base (English)
const base = langs[0];
const keys = Object.keys(data.strings);

// All characters are escaped uniformly. Mixing literals with escapes is disallowed: in C,
// the escape sequence is greedy and would consume the following hexadecimal digit of text.
const BS = String.fromCharCode(92);
function esc(s) {
    let out = '';
    for (const ch of s) {
        const c = ch.codePointAt(0);
        if (c > 0xffff) throw new Error('outside the BMP: ' + s);
        out += BS + 'x' + c.toString(16).padStart(4, '0');
    }
    return out;
}
function cmt(s) { return s.replace(/\*\//g, '* /'); }

// Native name of each language - exactly how the user sees it in the list. The code
// ("uk") means nothing to someone looking for their language, whereas the native name does.
const LNAME = {
    en: 'English',      uk: 'Українська',   ru: 'Русский',
    pl: 'Polski',       de: 'Deutsch',      fr: 'Français',
    es: 'Español',      it: 'Italiano',     pt: 'Português',
    cs: 'Čeština',      nl: 'Nederlands',   sv: 'Svenska',
    tr: 'Türkçe',       ro: 'Română',       hu: 'Magyar',
    el: 'Ελληνικά',     fi: 'Suomi',        da: 'Dansk',
    no: 'Norsk',        sk: 'Slovenčina',   bg: 'Български',
    hr: 'Hrvatski',     sl: 'Slovenščina',  sr: 'Srpski',
    et: 'Eesti',        lv: 'Latviešu',     lt: 'Lietuvių',
    ca: 'Català',
    zh: '简体中文',     ja: '日本語',       ko: '한국어',
    hi: 'हिन्दी',        ar: 'العربية',
};

// Symbian TLanguage for each code. A language without a counterpart here will not build -
// this is deliberate, so a table that cannot be reached does not silently appear.
const TLANG = {
    en: 'ELangEnglish',    uk: 'ELangUkrainian', ru: 'ELangRussian',
    pl: 'ELangPolish',     de: 'ELangGerman',    fr: 'ELangFrench',
    es: 'ELangSpanish',    it: 'ELangItalian',   pt: 'ELangPortuguese',
    cs: 'ELangCzech',      nl: 'ELangDutch',     sv: 'ELangSwedish',
    tr: 'ELangTurkish',    ro: 'ELangRomanian',  hu: 'ELangHungarian',
    el: 'ELangGreek',      fi: 'ELangFinnish',   da: 'ELangDanish',
    no: 'ELangNorwegian',  sk: 'ELangSlovak',    bg: 'ELangBulgarian',
    hr: 'ELangCroatian',   sl: 'ELangSlovenian', sr: 'ELangSerbian',
    et: 'ELangEstonian',   lv: 'ELangLatvian',   lt: 'ELangLithuanian',
    ca: 'ELangCatalan',
    zh: 'ELangPrcChinese', ja: 'ELangJapanese',  ko: 'ELangKorean',
    hi: 'ELangHindi',      ar: 'ELangArabic',
};

// Regional variants. Symbian distinguishes Austrian German, Belgian French,
// Brazilian Portuguese, etc. with separate constants, and a device configured
// for such a language would silently receive English without this table, even
// though we have a translation. Idea taken from PS1Emulator/src/symbian/i18n.cpp.
const ALIAS = {
    en: ['ELangAmerican', 'ELangAustralian', 'ELangCanadianEnglish',
         'ELangInternationalEnglish', 'ELangSouthAfricanEnglish',
         'ELangNewZealand'],
    de: ['ELangAustrian', 'ELangSwissGerman'],
    fr: ['ELangSwissFrench', 'ELangBelgianFrench', 'ELangCanadianFrench',
         'ELangInternationalFrench'],
    it: ['ELangSwissItalian'],
    pt: ['ELangBrazilianPortuguese'],
    es: ['ELangInternationalSpanish', 'ELangLatinAmericanSpanish'],
    nl: ['ELangBelgianFlemish'],
    sv: ['ELangFinlandSwedish'],
    tr: ['ELangCyprusTurkish'],
    el: ['ELangCyprusGreek'],
    no: ['ELangNorwegianNynorsk'],
    zh: ['ELangTaiwanChinese', 'ELangHongKongChinese'],
};

let h = `// GENERATED by tools/gen_strings.js from src/strings.json. Do not edit manually.
#ifndef OCSTR_H
#define OCSTR_H

#include <e32std.h>

enum TOcStrId
    {
`;
keys.forEach(k => { h += `    EStr${k},\n`; });
h += `    EStrCount
    };

// Selects the language once, via User::Language(). Unknown language defaults to English.
void OcStrInit();
// String in active language; if no translation exists - English fallback.
TPtrC OcStr(TInt aId);
// Built-in help in active language, otherwise English.
TInt OcHelpLineCount();
TPtrC OcHelpLine(TInt aIndex);
// Number of languages in the build and active code - for diagnostics.
TInt OcStrLanguageCount();
TPtrC OcStrActiveLanguage();
// Manual language selection. Index wraps around cyclically, so the caller can
// simply increment or decrement without worrying about bounds.
void OcStrSetLanguage(TInt aIndex);
TInt OcStrLanguageIndex();
// Native language name by index; without argument - active language.
TPtrC OcStrLanguageName(TInt aIndex);
TPtrC OcStrActiveLanguageName();

#endif
`;
fs.writeFileSync('src/ocstr.h', h, 'utf8');

let c = `// GENERATED by tools/gen_strings.js from src/strings.json. Do not edit manually.
//
// Tables use escapes of the form backslash-x-XXXX deliberately: this way content
// does not depend on how the compiler interprets source encoding. Readable
// source is src/strings.json.
//
// NULL in the table means "string missing in this language" - OcStr returns English.

#include <e32std.h>
#include "ocstr.h"

`;
langs.forEach(lang => {
    c += `static const TUint16* const KOcStr_${lang}[EStrCount] =\n    {\n`;
    keys.forEach(k => {
        const v = data.strings[k][lang];
        if (v === undefined || v === null) {
            c += `    NULL,   // ${cmt(data.strings[k][base])}\n`;
        } else {
            c += `    // ${cmt(v)}\n    (const TUint16*)L"${esc(v)}",\n`;
        }
    });
    c += `    };\n\n`;
});
const helpLangs = langs.filter(l => data.help[l]);
helpLangs.forEach(lang => {
    const lines = data.help[lang];
    c += `static const TUint16* const KOcHelp_${lang}[] =\n    {\n`;
    lines.forEach(v => {
        c += `    // ${cmt(v)}\n    (const TUint16*)L"${esc(v)}",\n`;
    });
    c += `    };\nstatic const TInt KOcHelpCount_${lang} = ${lines.length};\n\n`;
});

c += `static const TUint16* const* gStr = KOcStr_${base};
static const TUint16* const* gHelp = KOcHelp_${base};
static TInt gHelpCount = KOcHelpCount_${base};
static const TUint16* gActiveName = (const TUint16*)L"${esc(LNAME[base])}";

// Tables of all languages in a single array: enables manual selection.
// Order is the same as in src/strings.json, with English coming first.
static const TUint16* const* const KOcStrTable[] =
    {
LANGTABLE    };

static const TUint16* const* const KOcHelpTable[] =
    {
HELPTABLE    };

static const TInt KOcHelpCountTable[] =
    {
HELPCOUNT    };

static const TUint16* const KOcLangName[] =
    {
LANGNAMES    };

static TInt gLang = 0;

static void OcStrUse(TInt aIndex)
    {
    gLang = aIndex;
    gStr = KOcStrTable[aIndex];
    gHelp = KOcHelpTable[aIndex];
    gHelpCount = KOcHelpCountTable[aIndex];
    gActiveName = KOcLangName[aIndex];
    }

void OcStrSetLanguage(TInt aIndex)
    {
    const TInt n = OcStrLanguageCount();
    // Wrap around cyclically in both directions: scrolling the list should not
    // hit an edge, and negative index in C++ yields a negative remainder.
    TInt i = aIndex % n;
    if (i < 0)
        i += n;
    OcStrUse(i);
    }

TInt OcStrLanguageIndex()
    {
    return gLang;
    }

TPtrC OcStrLanguageName(TInt aIndex)
    {
    if (aIndex < 0 || aIndex >= OcStrLanguageCount())
        return TPtrC();
    return TPtrC(KOcLangName[aIndex]);
    }

TPtrC OcStrActiveLanguageName()
    {
    return TPtrC(KOcLangName[gLang]);
    }

void OcStrInit()
    {
    switch (User::Language())
        {
`;
langs.slice(1).forEach(lang => {
    const sym = TLANG[lang];
    if (!sym) throw new Error('no TLanguage for ' + lang);
    c += `        case ${sym}:
`;
    (ALIAS[lang] || []).forEach(a => { c += `        case ${a}:
`; });
    c += `            OcStrUse(${langs.indexOf(lang)});
            break;
`;
});
c += `        default:
            break;
        }
    }

TPtrC OcStr(TInt aId)
    {
    if (aId < 0 || aId >= EStrCount)
        return TPtrC();
    const TUint16* s = gStr[aId];
    if (!s)
        s = KOcStr_${base}[aId];      // partial language: fallback to English
    return TPtrC(s);
    }

TInt OcHelpLineCount()
    {
    return gHelpCount;
    }

TPtrC OcHelpLine(TInt aIndex)
    {
    if (aIndex < 0 || aIndex >= gHelpCount)
        return TPtrC();
    return TPtrC(gHelp[aIndex]);
    }

TInt OcStrLanguageCount()
    {
    return ${langs.length};
    }

TPtrC OcStrActiveLanguage()
    {
    return TPtrC(gActiveName);
    }
`;
// Table bodies. Language without help falls back to English: NULL here would mean
// an empty screen instead of text, rather than "no translation".
let langTable = '', helpTable = '', helpCount = '', langNames = '';
langs.forEach(l => {
    langTable += `    KOcStr_${l},\n`;
    const hl = data.help[l] ? l : base;
    helpTable += `    KOcHelp_${hl},\n`;
    helpCount += `    KOcHelpCount_${hl},\n`;
    if (!LNAME[l]) throw new Error('no native name for ' + l);
    langNames += `    // ${cmt(LNAME[l])}\n    (const TUint16*)L"${esc(LNAME[l])}",\n`;
});
c = c.replace('LANGTABLE', langTable)
     .replace('HELPTABLE', helpTable)
     .replace('HELPCOUNT', helpCount)
     .replace('LANGNAMES', langNames);

fs.writeFileSync('src/ocstr.cpp', c, 'utf8');

const filled = {};
langs.forEach(l => filled[l] = keys.filter(k => data.strings[k][l] != null).length);
console.log('languages:', langs.length, '| strings:', keys.length,
            '| help:', helpLangs.join(','));
console.log('filled:', langs.map(l => l + '=' + filled[l]).join(' '));
